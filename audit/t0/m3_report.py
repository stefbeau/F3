"""Write the M3 World3 port report (audit/m3-world3-port-report.md) with figures from real runs.

Run from the repository root:  uv run --group dev python audit/t0/m3_report.py
Reads tests/fixtures/w3_*.csv (exported from WorldDynamics.jl by audit/t0/world3_m3_export.jl), runs the four ported sectors alone
(A3.1) and the full coupled model (A3.2, A3.4, A3.5), and PyWorld3 unmodified for the second check (A3.3).
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from f3.sectors.s1_population import STATE_NAMES as S1_STATES, Inputs, PopulationSector  # noqa: E402
from f3.sectors.w3_agriculture import Agriculture  # noqa: E402
from f3.sectors.w3_capital import Capital  # noqa: E402
from f3.sectors.w3_pollution import Pollution  # noqa: E402
from f3.sectors.w3_resources import Resources  # noqa: E402
from f3.sectors.world3 import STATE_COLUMNS, run_world3  # noqa: E402
from tests.test_w3_pyworld3 import STOCKS, _compare, _pyworld3  # noqa: E402
from tests.w3_helpers import a31, grid_index, reference, relerr, s1_inputs, state_table  # noqa: E402

SECTORS = {
    "agriculture": (Agriculture, {"pop": "ld₊pop", "io": "ld₊io", "iopc": "ld₊iopc", "ppolx": "lfd₊ppolx"},
                    {"al": "ld₊al", "pal": "ld₊pal", "ai": "ai₊ai", "uil": "leuiu₊uil", "lfert": "lfd₊lfert", "pfr": "dlm₊pfr"}),
    "capital": (Capital, {"pop": "is₊pop", "p2": "js₊p2", "p3": "js₊p3", "fcaor": "is₊fcaor", "fioaa": "is₊fioaa",
                          "aiph": "js₊aiph", "al": "js₊al"}, {"ic": "is₊ic", "sc": "ss₊sc", "lufd": "js₊lufd"}),
    "non-renewable resources": (Resources, {"pop": "nr₊pop", "iopc": "nr₊iopc"}, {"nr": "nr₊nr"}),
    "persistent pollution": (Pollution, {"pcrum": "pp₊pcrum", "pop": "pp₊pop", "aiph": "pp₊aiph", "al": "pp₊al"},
                             {"ppapr1": "pp₊ppapr1", "ppapr2": "pp₊ppapr2", "ppapr3": "pp₊ppapr3", "ppol": "pp₊ppol"}),
}
SETNAME = {"1974": "1974 parameter set against WorldDynamics.jl `World3`",
           "2004": "2004 parameter set against WorldDynamics.jl `World3_03.scenario1`"}

L = ["# F3 — M3 World3 port: comparison report (agriculture, capital, non-renewable resources, persistent pollution)", "",
     "Generated by `audit/t0/m3_report.py` from real runs. Reference: WorldDynamics.jl v1.0.0 in the pinned environment `audit/env` "
     "(D-017), default solver options, exported by `audit/t0/world3_m3_export.jl`; the tight-tolerance run is reltol = abstol = 1e-8. "
     "Port: `f3/sectors/w3_*.py` and S1, classical RK4 inside each sector, loop step 0.25 year (D-003), explicit coupling at step "
     "boundaries (D-022). Tolerance +-2% (D-004). Variables are matched by name. Error = |port - reference| / |reference| at every 0.5-year "
     "point of 1900-2100 (401 points). The plan and the reading of every test were committed before any result (`docs/tracks/track-b.md`).", ""]

# ---------------------------------------------------------------- A3.1
L += ["## A3.1 each sector alone, recorded inputs, the reference's own initial state", "",
      "Inputs are the series the full WorldDynamics.jl run had (1/16-year grid, linear interpolation). Each cell: port against the default "
      "reference, max / mean, year of max; then port against the tight reference (max), and the reference's own default-against-tight "
      "difference (max).", ""]
a31_worst = {}
for ps in ("1974", "2004"):
    L += [f"### {SETNAME[ps]}", "", "| sector | state | port vs reference (max / mean) | year of max | port vs tight (max) | reference default vs tight (max) |",
          "|---|---|---|---|---|---|"]
    for sec, (cls, mapping, smap) in SECTORS.items():
        s, res, idx, ref, tight = a31(cls, ps, mapping, smap, {})
        for n, (e, yr, et, er, mean) in state_table(s, idx, ref, tight, smap).items():
            L.append(f"| {sec} | `{n}` | {100*e:.3f}% / {100*mean:.3f}% | {yr:.1f} | {100*et:.3f}% | {100*er:.3f}% |")
            a31_worst[(ps, n)] = e
    w = max((v, k) for k, v in a31_worst.items() if k[0] == ps)
    L += ["", f"All 14 states of the four sectors: worst gap to the default reference **{100*w[0]:.3f}%** (`{w[1][1]}`). "
          f"Pass criterion +-2%: **{'met' if w[0] <= 0.02 else 'NOT met'}**. (S1's own 15 states: `audit/s1-port-report.md`.)", ""]

# ---------------------------------------------------------------- A3.2
L += ["## A3.2 full coupled run, S1 plus the four sectors, 29 states, 1900-2100", ""]
runs = {}
for ps in ("1974", "2004"):
    states, res = run_world3(ps)
    runs[ps] = (states, res)
    ref, tight = reference(ps), reference(ps, "tight")
    idx = grid_index(res.time, ref["time"])
    L += [f"### {SETNAME[ps]}", "", "| state | max / mean | year of max | first year above 2% | vs tight reference (max) | reference default vs tight (max) |",
          "|---|---|---|---|---|---|"]
    over = []
    for n, col in STATE_COLUMNS.items():
        e, et, er = relerr(states[n][idx], ref[col]), relerr(states[n][idx], tight[col]), relerr(ref[col], tight[col])
        first = f"{ref['time'][int(np.argmax(e > 0.02))]:.1f}" if e.max() > 0.02 else "-"
        L.append(f"| `{n}` | {100*e.max():.3f}% / {100*e.mean():.3f}% | {ref['time'][int(e.argmax())]:.1f} | {first} | {100*et.max():.3f}% | {100*er.max():.3f}% |")
        if e.max() > 0.02:
            over.append((float(ref["time"][np.argmax(e > 0.02)]), n))
    worst = max((relerr(states[n][idx], ref[c]).max(), n) for n, c in STATE_COLUMNS.items())
    L += ["", f"Worst gap to the default reference **{100*worst[0]:.3f}%** (`{worst[1]}`). States above 2%: **{len(over)} of 29**"
          + (f"; the first criterion failure is in {min(over)[0]:.1f} (`{min(over)[1]}`)." if over else ".")
          + f" Pass criterion +-2%: **{'met' if not over else 'NOT met (A3.2 FAILED)'}**. The reference's own default-against-tight difference is at most "
          f"{100*max(relerr(ref[c], tight[c]).max() for c in STATE_COLUMNS.values()):.2f}% on any state, so the gap is not the reference's solver: "
          "the port against the tight reference is as large as against the default one.", ""]

# step scan (diagnostic)
L += ["### Diagnostic after the failure: the same run at smaller loop steps", "",
      "Not part of the acceptance test and not a revised criterion; it shows where the gap comes from. Worst of 29 states, and the number of "
      "states above 2%.", "", "| loop step (year) | 1974 worst (state) | 1974 states above 2% | 2004 worst (state) | 2004 states above 2% | run time 2004 (s) |",
      "|---|---|---|---|---|---|"]
for dt in (0.25, 0.125, 0.0625, 0.03125):
    cells, t2004 = [], None
    for ps in ("1974", "2004"):
        ref = reference(ps)
        a = time.perf_counter()
        st, res = run_world3(ps, dt=dt)
        el = time.perf_counter() - a
        if ps == "2004":
            t2004 = el
        idx = grid_index(res.time, ref["time"])
        w = {n: relerr(st[n][idx], ref[c]).max() for n, c in STATE_COLUMNS.items()}
        k = max(w, key=w.get)
        cells += [f"{100*w[k]:.3f}% (`{k}`)", str(sum(v > 0.02 for v in w.values()))]
    L.append(f"| {dt} | " + " | ".join(cells) + f" | {t2004:.2f} |")
L += ["", "The gap roughly halves when the step halves down to 0.0625 (first order, as D-022 measured for S1 alone; below that the 1974 gap stops falling because the reference's own solver error, 1.61% on `fcfpc1`, takes over): it is the start-of-step coupling of D-022, not an "
      "equation difference (every sector alone is within 0.13%). At step 0.0625 and below the criterion would be met for 1974 and for 2004. "
      "A finer loop step, or a predictor-corrector, is a design change for the editor; it is listed in the review, not applied.", ""]

# ---------------------------------------------------------------- A3.4
L += ["## A3.4 (b) S1 inside the full run against S1 alone with recorded inputs", "",
      "Criterion from the plan: within 0.25%. Prediction recorded before the run: fails, because D-022 measured the start-of-step coupling "
      "error of S1 at 0.25 year as 1.04% (1974) and 0.93% (2004).", "", "| set | worst of S1's 15 states | state | year of max | first year above 0.25% |", "|---|---|---|---|---|"]
for ps in ("1974", "2004"):
    states, res = runs[ps]
    s = s1_inputs(ps)
    alone = PopulationSector(ps).run(Inputs(s["time"], s["dr₊fpc"], s["br₊sopc"], s["dr₊iopc"], s["dr₊ppolx"]), dt=0.25)
    w = {n: relerr(states[n], alone[n]) for n in S1_STATES}
    k = max(w, key=lambda n: w[n].max())
    row = f"| {ps} | {100*w[k].max():.3f}% | `{k}` | {res.time[int(w[k].argmax())]:.2f} |"
    over = [n for n in S1_STATES if w[n].max() > 0.0025]
    first = min(res.time[int(np.argmax(w[n] > 0.0025))] for n in over) if over else None
    L.append(row + (f" {first:.2f} |" if first is not None else " - |"))
L += ["", "A3.4 (b) FAILED for both sets (see the table); A3.4 (a), the existing tests, pass (see `docs/tracks/track-b.md` for the counts).", ""]

# ---------------------------------------------------------------- A3.3
L += ["## A3.3 second check: PyWorld3 1.1 unmodified, dt = 0.05", "",
      "Twelve main stocks of the full coupled port (step 0.25, WorldDynamics.jl initial state) against PyWorld3, max over 1900-2100 (year). "
      "The row with the pollution delay start matched is a **labelled diagnostic**: a runtime override of the start value of PyWorld3's "
      "third-order pollution delay on the instance (as CLAUDE.md and `audit/t0/pyworld3_t0.py`); no PyWorld3 code is edited or copied. The 2004 "
      "rows are diagnostic as in S1: PyWorld3 does not ship that variant, so its parameters and tables are overridden on an instance "
      "(`tests/test_w3_pyworld3.py`), which makes it not an independent implementation of the 2004 model.", "",
      "| set | start-up | " + " | ".join(STOCKS) + " |", "|---|---|" + "---|" * len(STOCKS)]
import io
import contextlib
for ps in ("1974", "2004"):
    states, res = runs[ps]
    ref = reference(ps)
    w0 = _pyworld3(ps)
    ppgr_wd = float(ref["pp₊ppapr3"][0]) * 3.0 / float(w0.pptd1)
    w1 = _pyworld3(ps, ppgr_start=ppgr_wd)
    for label, w in (("as shipped", w0), ("pollution delay start matched (diagnostic)", w1)):
        with contextlib.redirect_stdout(io.StringIO()):
            out = _compare(ps, w, states, res, label)
        L.append(f"| {ps}{' (diagnostic)' if ps == '2004' else ''} | {label} | " + " | ".join(f"{100*out[k][0]:.2f}% ({out[k][1]:.0f})" for k in STOCKS) + " |")
    st2, res2 = run_world3(ps, dt=0.0625)
    with contextlib.redirect_stdout(io.StringIO()):
        out = _compare(ps, w1, st2, res2, "x")
    L.append(f"| {ps}{' (diagnostic)' if ps == '2004' else ''} | matched, port at loop step 0.0625 (post-hoc diagnostic) | " + " | ".join(f"{100*out[k][0]:.2f}% ({out[k][1]:.0f})" for k in STOCKS) + " |")
L += ["", "Reading: with the pollution start-up matched and the loop step of the plan, the 1974 set is within 2% on ten of the twelve stocks and "
      "above it on `ic` (3.39%) and `sc` (2.42%), both late in the run; this is the same coupling error as in A3.2, and the post-hoc row at "
      "step 0.0625 shows it shrinks with the step. As shipped, `ppol` differs by 373% in 1906, the start-up difference of CLAUDE.md. "
      "**A3.3 FAILED for the 1974 set at the plan's step.**", ""]

# ---------------------------------------------------------------- A3.5
L += ["## A3.5 run time", ""]
L += ["| run | median of 5 (s) | min / max (s) |", "|---|---|---|"]
for ps, t0 in (("2004", 1900.0), ("1974", 1900.0), ("2004", 1970.0)):
    run_world3(ps, t0=t0)
    ts = []
    for _ in range(5):
        a = time.perf_counter()
        run_world3(ps, t0=t0)
        ts.append(time.perf_counter() - a)
    L.append(f"| set {ps}, {t0:.0f}-2100, step 0.25, five sectors, one core | {np.median(ts):.2f} | {min(ts):.2f} / {max(ts):.2f} |")
L += ["", "Measured on this machine (Windows 11, Python 3.12, one core, pure Python loops, no vectorisation). At 0.5 s a run, a thousand-run Monte Carlo "
      "is about 8 minutes on one core; at the step 0.0625 that the diagnostic suggests (about 2 s) about 35 minutes. The plan's guess of 5-10 s "
      "per run was too high by an order of magnitude at the plan's step. This figure does not include FaIR, S3 or the Earth4All sectors.", ""]

(ROOT / "audit" / "m3-world3-port-report.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
print("\n".join(L))
