"""Generates audit/m4-earth4all-port-report.md from real runs of the M4 ports (plan: docs/tracks/track-c-plan.md).

    PYTHONPATH=. PYTHONUTF8=1 uv run --group dev python audit/t0/m4_report.py

Everything in the report is measured here, except the sentences marked (inferred). Earth4All.jl's own error against Vensim is beside every
figure (D-018); the port is never said to reproduce Vensim.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, ".")
import numpy as np

from audit.t0.e4a_ladder import case_of
from tests.e4a_helpers import FINE, FIX, SCENARIOS, compare, economy_run, grid_index, reference, rel_err, run_alone, signals, vensim_error, worst

KEYS = ["output", "inventory", "finance", "labourmarket", "public", "demand", "energy", "other"]
STEP = json.load(open(FIX / "e4a_step_effect.json", encoding="utf-8"))
L = []
w = L.append


def pct(x):
    return "n/a (reference near 0)" if x is None or x == float("inf") else f"{100 * x:.3f}%"


def vz(scen, key, name):
    v = vensim_error(scen).get((key, name))
    if not v or v["all_zero"] == "true":
        return "identically zero in Vensim"
    return f"p95 {100 * float(v['p95']):.2f}%, max {100 * float(v['maximum']):.2f}%"


w("# F3 M4: reused Earth4All sectors, port comparison report (Track C)\n")
w("Generated by `audit/t0/m4_report.py` from real runs. Reference: Earth4All.jl commit `16f37d0` (MIT) in the pinned environment `audit/env-earth4all`, "
  "Euler at 1/64 year, 1980-2100, exported by `audit/t0/earth4all_m4_export.jl` (fixtures `tests/fixtures/e4a_*.csv`). Ports: `f3/sectors/e4a_*.py`, generated from the Julia "
  "sources by `audit/t0/e4a_translate.py` (the source line of each equation is beside it). Plan and readings written before any port: `docs/tracks/track-c-plan.md`. "
  "Tolerance +-2% (D-004) at every 0.5-year point of 1980-2100, true relative error; near-zero rule 1e-6 x max|reference|.\n")
w("**Caveat required by D-018.** Earth4All.jl follows the Vensim output closely for most variables but not for all (demand, energy, labour-market flows deviate most). "
  "The tests here compare the F3 port with Earth4All.jl, not with Vensim; nothing in this report says that the port reproduces Vensim. "
  "Earth4All.jl's own error against Vensim (true relative error from the package's own comparison, names and figures only, D-014) is given beside the figures.\n")

# --- section 1: sectors alone
w("## 1. A4.1 each sector alone (recorded inputs by name)\n")
w("Runs: **S0** = the port with the reference's own scheme (Euler 1/64 year), recorded inputs on the reference's 1/64 grid (tests the equations); "
  "**S1** = RK4 at 1/64 year (step-free limit; S1 minus S0 is the reference's own Euler error); **S2** = RK4 at the loop step 0.25 year (one step, the F3 default of S1 and World3); "
  "**S3** = the rule recorded in `docs/tracks/track-c.md` (written into the plan before the run): Euler with an internal sub-step of 1/64 year inside the 0.25-year loop step. "
  "Worst criterion variable (states and headline variables of the plan table) and the variables above 2%.\n")
w("| sector | scen | S0 worst | S1 worst (above 2%) | S2 worst (above 2%) | S3 (rule) worst | Earth4All.jl vs Vensim for the S3-worst variable |")
w("|---|---|---|---|---|---|---|")
S3 = {}
for key in KEYS:
    case = case_of(key)
    for scen in SCENARIOS:
        s0 = worst(compare(run_alone(key, scen, FINE, "euler", None)[1], "e4a_" + key, scen, case.criterion))
        s3rows = compare(run_alone(key, scen, 0.25, "euler", None)[1], "e4a_" + key, scen, case.criterion)
        s3w = worst(s3rows)
        S3[(key, scen)] = s3rows
        r1, r2 = STEP[f"{key}|S1|{scen}"], STEP[f"{key}|S2|{scen}"]
        f1 = ", ".join(f"{n} {'inf' if a[0] is None else a[0]}% ({a[1]})" for n, a in r1["above_2pct"].items()) or "none"
        f2 = ", ".join(f"{n} {'inf' if a[0] is None else a[0]}% ({a[1]})" for n, a in r2["above_2pct"].items()) or "none"
        w(f"| {key} | {scen} | {s0.name} {pct(s0.max_err)} | {r1['worst']} {r1['worst_pct']}% ; above: {f1} | {r2['worst']} {r2['worst_pct']}% ; above: {f2} | "
          f"{s3w.name} {pct(s3w.max_err)} ({s3w.year_of_max}) | {vz(scen, key, s3w.name)} |")
w("\n(the year in brackets is the first year above 2%). All states and headline variables of all eight sectors are within 2% under S0 and S3 in both scenarios; **no sector fails A4.1 under the rule**. "
  "S1 and S2 (RK4) exceed 2% in output (`OGR`), inventory (`IR`), finance (`ISR`, `CBSR`, `PU`), labour market (`PURA`, `UR`, `UNEM`, GL also `WARA`, `WEOCLR`, `WSO`, `WASH`, `OPWO`, `AGIW`), public (`RTFPUA`), demand (`CFWB`, `ETF2022`, `CFGB`) and energy (GL `FEP`, `UFF`); `other` is within 0.011%. "
  "(Inferred, not tested further:) these are variables near zero or at a switch or kink where the reference's own Euler step error is large, so a more accurate integrator departs from the reference. "
  "The loop-step effect alone is S2 minus S1 and is small (largest: `RTFPUA`, 1.2 points).\n")
w("**Rule (stated before the run, applied once).** No RK4 rung of the ladder (0.125, 0.0625, 0.03125 year) brings every state and headline variable within 2% (`audit/t0/e4a_ladder.py`); Euler 1/64 does. "
  "So every M4 sector runs Euler with a 1/64-year internal sub-step inside the 0.25-year loop step (D-031 pattern; D-003 and D-022 not edited). This is a selection on the pre-stated ladder, not a relaxation: the tolerance is still 2%. "
  "**Correction made after the first run (labelled in `docs/tracks/track-c.md`):** my first fixture put the recorded inputs on a 1/16-year grid; with that grid S0 failed in output (TLTL), finance and labour market, because the Euler reference reads its inputs every 1/64 year; I amended the fixture to the 1/64 grid; criteria and tolerance were not touched.\n")

# informational: all variables
w("### 1.1 Every variable of the sector (informational, not criterion), S3\n")
w("| sector | scen | variables | worst variable | error |")
w("|---|---|---|---|---|")
from tests.e4a_helpers import all_variables
for key in KEYS:
    for scen in SCENARIOS:
        s, res = run_alone(key, scen, 0.25, "euler", None)
        names = [n for n in all_variables(key, scen) if ("e4a_" + key, n) in res.series]
        rows = compare(res, "e4a_" + key, scen, names)
        live = [r for r in rows.values() if not r.excluded]
        ww = max(live, key=lambda r: r.max_err)
        ex = [r.name for r in rows.values() if r.excluded]
        w(f"| {key} | {scen} | {len(live)} (+{len(ex)} identically zero: {', '.join(ex) or 'none'}) | {ww.name} | {pct(ww.max_err)} |")

# --- timing
t = time.perf_counter()
run_alone("energy", "tltl", 0.25, "euler", None)
w(f"\nTiming (one core, this machine, one run, 1980-2100): energy alone, loop step 0.25 with internal Euler 1/64: {time.perf_counter() - t:.1f} s.\n")

# --- A4.2
w("## 2. A4.2 switches (output: `OWECC`, `OWELC`; public: `OWTFP`; `EDROTA2022`)\n")
w("Three parameters `SW_OWECC`, `SW_OWELC`, `SW_OWTFP` (default 1 = Earth4All.jl exactly, 0 = channel off) multiply the channel coefficients; they are the only structural addition to the transcribed equations (marked in the module headers). "
  "`EDROTA2022` = 0.003 per year is documented in the `e4a_public` docstring and is a parameter (`params={'EDROTA2022': x}`).\n")
w("| check | result |")
w("|---|---|")
for key, chans in (("output", {"SW_OWECC": 0.0, "SW_OWELC": 0.0}), ("public", {"SW_OWTFP": 0.0})):
    for scen in SCENARIOS:
        sg = signals(scen)
        held = {"OW": np.full_like(sg["time"], 1.35)}
        _, ron = run_alone(key, scen, 0.25, "euler", None, overrides=held)
        _, roff = run_alone(key, scen, 0.25, "euler", None, switches=chans, overrides=held)
        nm = "e4a_" + key
        d = max(float(np.max(np.abs(ron.series[k] - roff.series[k]))) / max(float(np.max(np.abs(roff.series[k]))), 1e-300) for k in ron.series if k[0] == nm)
        w(f"| {key} {scen}: channels on with OW held at 1.35 vs off, worst difference relative to series scale | {d:.2e} (criterion 1e-9) |")
        _, roff2 = run_alone(key, scen, 0.25, "euler", None, switches=chans)
        _, ron2 = run_alone(key, scen, 0.25, "euler", None)
        ref = reference(scen)
        idx = grid_index(roff2.time, ref["time"])
        early = ref["time"] <= 2022 + 1e-9
        case = case_of(key)
        we = 0.0
        eff = {}
        for n in case.criterion:
            e = rel_err(roff2.series[(nm, n)][idx], ref[f"{key}.{n}"])
            if e is not None:
                we = max(we, float(e[early].max()))
            dd = rel_err(roff2.series[(nm, n)][idx], ron2.series[(nm, n)][idx])
            if dd is not None and dd.max() > 1e-12:
                eff[n] = float(dd.max())
        w(f"| {key} {scen}: channels off vs Earth4All.jl up to 2022 (channels inactive there) | worst {we:.1e} (no off-run reference exists; the post-2022 effect is reported, not judged) |")
        w(f"| {key} {scen}: effect of switching off on criterion variables, max over 1980-2100 | " + ", ".join(f"{n} {100 * v:.1f}%" for n, v in eff.items()) + " |")
w("\n**What A4.2 does not show.** Earth4All.jl has no run with the channels off, so \"with the channels off the sector still passes A4.1\" is established only up to 2022, where the channels are structurally inactive; after 2022 the off case is by construction different from the reference (the effect above) and no reference exists to compare it with. "
  "The baseline caveat of D-023 stands: the channels divide the warming by the constant 1.35 degrees C and the baseline of F3's own warming against it is not checked. "
  "Nothing in this report is a damage estimate; it is the size of the three channels in the recorded Earth4All.jl warming path.\n")
for scen in SCENARIOS:
    _, a = run_alone("public", scen, 0.25, "euler", None)
    _, b = run_alone("public", scen, 0.25, "euler", None, params={"EDROTA2022": 0.0})
    w(f"- `EDROTA2022` {scen}: setting it to 0 lowers `TFPEE5TA` in 2100 by {100 * (1 - b.series[('e4a_public', 'TFPEE5TA')][-1] / a.series[('e4a_public', 'TFPEE5TA')][-1]):.1f}% (it adds 0.003 x (1 + 0.5 x (SC/SC1980 - 1)) per year to the domestic rate of technological advance from 2022).")

# --- A4.3
w("\n## 3. A4.3 demand: component comparison with Vensim (Earth4All.jl against Vensim)\n")
w("From the package's own comparison (`read_vensim_dataset`, D-014) at run time, true relative error |julia - vensim| / |vensim| per variable; points where |vensim| is below 1e-6 of its series maximum are excluded (counted). Names and figures only. D-004 is not relaxed: variables above 2% are listed as deviations.\n")
for scen in SCENARIOS:
    ve = vensim_error(scen)
    rows = [r for (sec, n), r in ve.items() if sec == "demand"]
    live = [r for r in rows if r["all_zero"] != "true"]
    zero = [r["variable"] for r in rows if r["all_zero"] == "true"]
    meds = sorted(float(r["median"]) for r in live)
    p95s = sorted(float(r["p95"]) for r in live)
    w(f"**{scen.upper()}**: {len(live)} variables compared, {len(zero)} identically zero in Vensim ({', '.join(zero) or 'none'}); median of per-variable medians {100 * meds[len(meds) // 2]:.3f}%, median of per-variable p95 {100 * p95s[len(p95s) // 2]:.3f}%; "
      f"p95 above 2%: {sum(float(r['p95']) > 0.02 for r in live)}; maximum above 2%: {sum(float(r['maximum']) > 0.02 for r in live)}; excluded-point counts range {min(int(r['excluded']) for r in rows)} to {max(int(r['excluded']) for r in rows)} of 7681.\n")
    w("| variable | median | p95 | max | year of max | points excluded |")
    w("|---|---|---|---|---|---|")
    for r in sorted(live, key=lambda r: -float(r["p95"])):
        if float(r["p95"]) > 0.005 or float(r["maximum"]) > 0.02:
            w(f"| {r['variable']} | {100 * float(r['median']):.3f}% | {100 * float(r['p95']):.2f}% | {100 * float(r['maximum']):.2f}% | {float(r['year_of_max']):.1f} | {r['excluded']} |")
    w("\n(variables with p95 above 0.5% or maximum above 2% shown; every demand variable's figures are in `audit/data/e4a_vs_vensim_" + scen + ".csv`)\n")

# --- A4.4
w("## 4. A4.4 labour market: T2 on the port, D-016 definition (employed = WF, working-age = WAP)\n")
for scen in SCENARIOS:
    _, res = run_alone("labourmarket", scen, 0.25, "euler", None)
    ref = reference(scen)
    idx = grid_index(res.time, ref["time"])
    WF = res.series[("e4a_labourmarket", "WF")][idx]
    WAP = res.series[("e4a_labourmarket", "WAP")][idx]
    AV = res.series[("e4a_labourmarket", "AVWO")][idx]
    w(f"- {scen}: WF > WAP in {int(np.sum(WF > WAP))} of {len(WF)} points; maximum WF/WAP {np.max(WF / WAP):.4f} (the reference's own fixture: {np.max(ref['labourmarket.WF'] / ref['labourmarket.WAP']):.4f}); maximum excess of WF over AVWO {100 * np.max(np.maximum(WF / AV - 1, 0)):.3f}% (audit T2: up to 0.59%).")
w("WAP is the recorded `A20PA` of Earth4All.jl's population sector (a replaced sector). **T2 is met on the port with Earth4All's own population.** With World3's cohorts the working-age series differs (D-023: measured 12 points in 1980, under 1 point in 2020), so T2 has to be re-run on the coupled model with adapters, which is M6; the effect of S3's automation input is **not tested** (S3 is not coupled before M6). The D-016 caveat stands: a different pair of variables could give a different answer.\n")

# --- A4.5
w("## 5. A4.5 coupled economy (eight reused sectors as one group, replaced-sector signals recorded)\n")
w("Group `f3.sectors.e4a_economy.E4AEconomy` (D-031 pattern): members advanced with sub-steps (plan ladder, Euler 1/64 the rung at which each member alone passes) inside the 0.25-year loop step, explicit start-of-sub-step coupling among members; replaced-sector signals (`POP`, `GDPP`, `EGDPP`, `A20PA`, `OW`, `CAC`, `COFO`, `IPP`) from a ReplaySector. Start-up values of the cross-member signals at 1980 are the recorded ones (labelled).\n")
w("| variable | TLTL max (year of max, first year above 2%) | GL max (year of max, first year above 2%) | Earth4All.jl vs Vensim TLTL | GL |")
w("|---|---|---|---|---|")
from tests.test_e4a_economy import _economy_rows
R = {s: _economy_rows(s) for s in SCENARIOS}
for k in R["tltl"][0]:
    cells = []
    for s in SCENARIOS:
        e = R[s][0][k]
        t_ = R[s][3]["time"]
        if e is None:
            cells.append("identically zero")
            continue
        ab = np.where(e > 0.02)[0]
        cells.append(f"{100 * e.max():.3f}% ({t_[int(e.argmax())]}, {t_[ab[0]] if len(ab) else '-'})")
    sec, _, n = k.partition(".")
    w(f"| {k} | {cells[0]} | {cells[1]} | {vz('tltl', sec, n) if '.' in k and sec in KEYS else ''} | {vz('gl', sec, n) if '.' in k and sec in KEYS else ''} |")
w("\n**A4.5 FAILED** (strict xfail in `tests/test_e4a_economy.py`): GDP, GDP per person, public spending (`GS`, `PSP`) exceed 2% in both scenarios, and the inequality index (`INEQ`, `INEQI`) in Giant Leap, in the last decades; the energy mix is exact. Sizes in the table. "
  "Each member alone is within 0.0000% with recorded inputs, so the gap arises in the coupling of the members. A post-hoc labelled scan of finer group sub-steps (1/128, 1/256) is worse, not better (GDP 2.8% and 3.1% TLTL; GL `FEP` 13% and 20% at its kink), so no rung of the pre-stated ladder meets 2%. "
  "(Inferred, not tested:) the reference solves all connections simultaneously within one Euler step while the group lets each member read the others' values from the start of the sub-step; with the economy's feedback loops this one-sub-step lag accumulates. "
  "Per the plan the criterion is not adjusted; the options for the editor are in `docs/tracks/track-c-review.md`.\n")
states_w = {}
for s in SCENARIOS:
    rows, res, idx, ref = R[s]
    from tests.test_e4a_economy import STATES, _series
    for sec, names in STATES.items():
        for n in names:
            e = rel_err(_series(res, sec, n)[idx], ref[f"{sec}.{n}"])
            if e is not None:
                states_w[(s, f"{sec}.{n}")] = float(e.max())
for s in SCENARIOS:
    top = sorted(((v, k[1]) for k, v in states_w.items() if k[0] == s), reverse=True)[:6]
    w(f"- states of the eight sectors in the group, {s}: worst " + ", ".join(f"{n} {100 * v:.3f}%" for v, n in top))

# --- A4.6
w("\n## 6. A4.6 known deviations of Earth4All.jl from Vensim (reported, D-018)\n")
for scen in SCENARIOS:
    ve = vensim_error(scen)
    inq = ve[("demand", "INEQ")]
    w(f"- {scen}: inequality index `INEQ` (demand): p95 {100 * float(inq['p95']):.2f}%, maximum {100 * float(inq['maximum']):.2f}% in {float(inq['year_of_max']):.1f}; `INEQI`: same. "
      f"The well-being index belongs to the replaced wellbeing sector and is not ported; its Earth4All.jl-vs-Vensim deviation (4.37% TLTL, 2.77% GL at the worst point) is in `audit/T0-FINDINGS.md` and D-018.")
allrows = []
for scen in SCENARIOS:
    ve = vensim_error(scen)
    for (sec, n), r in ve.items():
        if r["all_zero"] != "true" and float(r["p95"]) > 0.02:
            allrows.append((scen, sec, n, float(r["p95"]), float(r["maximum"])))
w(f"\nAcross the eight ported sectors, variables whose Earth4All.jl-vs-Vensim p95 exceeds 2% (true relative error): TLTL {sum(1 for r in allrows if r[0] == 'tltl')}, GL {sum(1 for r in allrows if r[0] == 'gl')} of 295 compared in each. By sector: " +
  "; ".join(f"{sec} {sum(1 for r in allrows if r[1] == sec and r[0] == 'tltl')}/{sum(1 for r in allrows if r[1] == sec and r[0] == 'gl')}" for sec in KEYS) + " (TLTL/GL). **The F3 port is measured against Earth4All.jl; it does not reproduce Vensim to within 2% where Earth4All.jl itself does not.**\n")

w("## 7. What \"other\" is for (D-016: not assessed)\n")
w("Finding (from `audit/data/earth4all_cross_sector_links.csv` and the port): the only variable of \"other\" that any sector reads is `CTA` (cost of the turnarounds = cost of food + cost of energy), read by public: `ECTAF2022 = max(0, CTA - CTA2022)`, which sets the TFP loss from unprofitable activity (`PLUA`, `RTFPUA`) and, through demand's extra taxes (`ETTAF2022`), the government's budget. "
  "The other six variables (`FB15`, `PB15`, `LK`, `IEL`, `RGGDPP`, `PGDPP`) are performance indicators with no downstream use. So \"other\" matters for the economy through one variable and is ported (7 equations, 1 state); it is within 0.011% in every run. "
  "Its input `COFO` (cost of food) comes from the replaced foodland sector: D-023 notes World3 agriculture has no equivalent, which is an open point for M6.\n")
w("## 8. Open points\n")
w("- `IC2022` (demand L159) has the ramp end `2020 + IPP` where the other policy ramps use `2022 + IPP`; copied as in Earth4All.jl (so the reference is reproduced); whether Vensim has it was not checked. In both scenarios the ramp's coefficient `GEIC` is 0 (TLTL) or 0.02 (GL); `IC2022` is identically zero in TLTL.")
w("- The warming baseline (D-023): the channels divide by the constant 1.35; F3's own warming baseline is not checked.")
w("- Provisional decision N4 and the sub-step rule: drafted in `docs/tracks/track-c.md`.")
Path("audit/m4-earth4all-port-report.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
